const roles = JSON.parse(fs.readFileSync(rolesPath, "utf8"));
const nightKeys = fs
  .readFileSync("./data_parse/_nights.txt", "utf8")
  .split("\n");

if (nightKeys.length !== NIGHTS.length) {
  console.error(
    `Mismatch: ${nightKeys.length} night keys but ${NIGHTS.length} translations.`,
  );
  process.exit(1);
}
const nightMap = new Map(nightKeys.map((en, i) => [en, NIGHTS[i]]));

const missing = new Set();
const translateToken = (t) => {
  if (TOKENS[t] !== undefined) return TOKENS[t];
  missing.add(`token: ${t}`);
  return t;
};
const translateNight = (t) => {
  if (nightMap.has(t)) return nightMap.get(t);
  missing.add(`night: ${t}`);
  return t;
};

for (const role of roles) {
  if (Array.isArray(role.reminders))
    role.reminders = role.reminders.map(translateToken);
  if (Array.isArray(role.remindersGlobal))
    role.remindersGlobal = role.remindersGlobal.map(translateToken);
  if (role.firstNightReminder)
    role.firstNightReminder = translateNight(role.firstNightReminder);
  if (role.otherNightReminder)
    role.otherNightReminder = translateNight(role.otherNightReminder);
}

fs.writeFileSync(rolesPath, JSON.stringify(roles, null, 2) + "\n", "utf8");

if (missing.size) {
  console.log(`Untranslated (${missing.size}):`);
  for (const m of missing) console.log("  " + m);
} else {
  console.log("All reminders translated successfully.");
}
